#!/bin/bash

# Repair contract for migrations/1790190839.sh, against the failures reported
# on the original change: unattended updates must not prompt for a passphrase,
# cryptdevice=...:name: must not wedge the migration queue, commented-out
# parameters must not count as cryptdevices, and the post-build check must read
# the generated boot artifacts rather than recompute from the edited config.

set -euo pipefail

source "$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)/base-test.sh"

migration="$ROOT/migrations/1790190839.sh"
helper="$ROOT/install/helpers/luks-trim.sh"
scratch=$(mktemp -d)
trap 'rm -rf "$scratch"' EXIT
mkdir -p "$scratch/bin" "$scratch/state" "$scratch/uki"

export PATH="$scratch/bin:$ROOT/bin:$PATH"
export CALL_LOG="$scratch/calls"
export OMARCHY_PATH="$ROOT"
export OMARCHY_LUKS_TRIM_LIMINE_CONF="$scratch/limine"
export OMARCHY_LUKS_TRIM_MARKER="$scratch/state/1790190839"
export OMARCHY_LUKS_TRIM_BOOT_CONF="$scratch/boot-limine.conf"
export OMARCHY_LUKS_TRIM_UKI_DIR="$scratch/uki"
trim_options="allow-discards,no-read-workqueue,no-write-workqueue"

cat > "$scratch/bin/sudo" <<'SH'
#!/bin/bash

printf 'sudo %s\n' "$*" >> "$CALL_LOG"
exec "$@"
SH

cat > "$scratch/bin/omarchy-state" <<'SH'
#!/bin/bash

[[ $* == "set reboot-required" ]] || exit 99
printf 'state %s\n' "$*" >> "$CALL_LOG"
SH

cat > "$scratch/bin/omarchy-cmd-missing" <<'SH'
#!/bin/bash

[[ ${BOOT_TOOLS_MISSING:-0} == "1" ]] || exit 1
exit 0
SH

cat > "$scratch/bin/limine-mkinitcpio" <<'SH'
#!/bin/bash

printf 'limine-mkinitcpio\n' >> "$CALL_LOG"
[[ ${REBUILD_FAIL:-0} == "0" ]] || exit 1
[[ ${SKIP_ARTIFACT:-0} == "0" ]] || exit 0
{
  printf '# generated by limine-mkinitcpio\n'
  grep -o 'KERNEL_CMDLINE\[[^]]*\]+="[^"]*"' "$OMARCHY_LUKS_TRIM_LIMINE_CONF" |
    sed -E 's/^KERNEL_CMDLINE\[([^]]*)\]\+="([^"]*)"/cmdline: \2/'
} > "$OMARCHY_LUKS_TRIM_BOOT_CONF"
SH

cat > "$scratch/bin/cryptsetup" <<'SH'
#!/bin/bash

printf 'cryptsetup %s\n' "$*" >> "$CALL_LOG"
[[ ${REFRESH_FAIL:-0} == "0" ]]
SH

chmod +x "$scratch/bin/"*

regenerate_boot_conf() {
  {
    printf '# generated by limine-mkinitcpio\n'
    grep -o 'KERNEL_CMDLINE\[[^]]*\]+="[^"]*"' "$OMARCHY_LUKS_TRIM_LIMINE_CONF" |
      sed -E 's/^KERNEL_CMDLINE\[([^]]*)\]\+="([^"]*)"/cmdline: \2/'
  } > "$OMARCHY_LUKS_TRIM_BOOT_CONF"
}

reset_fixture() {
  : > "$CALL_LOG"
  rm -f "$OMARCHY_LUKS_TRIM_MARKER"
  cat > "$OMARCHY_LUKS_TRIM_LIMINE_CONF" <<'CONF'
KERNEL_CMDLINE[default]+=" root=UUID=keep-me rw cryptdevice=UUID=keep-me:omarchy_root rootflags=subvol=@"
BOOT_ORDER="linux-omarchy, *, *fallback, Snapshots"
ENABLE_UKI=yes
CONF
  regenerate_boot_conf
}

# No terminal unless a test provides one.
run_migration() {
  bash -euo pipefail "$migration" < /dev/null > "$scratch/output" 2>&1
}

run_migration_pty() {
  script -qec "bash -euo pipefail $(printf '%q' "$migration")" /dev/null > "$scratch/output" 2>&1
}

assert_options_exactly_once() {
  local file="$1" option
  for option in allow-discards no-read-workqueue no-write-workqueue; do
    [[ $(grep -o "$option" "$file" | wc -l) == 1 ]] ||
      fail "$option appears exactly once in $file" "$(<"$file")"
  done
}

require_command script

# omarchy update runs under script(1), so the terminal gate cannot tell an
# unattended run from an operator. OMARCHY_UPDATE_UNATTENDED=1 is the signal
# the update sets, and the migration must never prompt then.
reset_fixture
if ! OMARCHY_UPDATE_UNATTENDED=1 run_migration_pty; then
  fail "an unattended update under a terminal must not fail" "$(<"$scratch/output")"
fi
! grep -q '^cryptsetup' "$CALL_LOG" ||
  fail "an unattended update never asks for the passphrase" "$(<"$CALL_LOG")"
grep -Fq "cryptdevice=UUID=keep-me:omarchy_root:$trim_options" "$OMARCHY_LUKS_TRIM_LIMINE_CONF" ||
  fail "an unattended update still repairs the kernel cmdline" "$(<"$OMARCHY_LUKS_TRIM_LIMINE_CONF")"
grep -Fxq 'state set reboot-required' "$CALL_LOG" ||
  fail "an unattended update defers to the next boot" "$(<"$CALL_LOG")"
[[ -f $OMARCHY_LUKS_TRIM_MARKER ]] || fail "an unattended update records completion"
pass "an unattended update under a terminal never prompts and defers to the next boot"

# The encrypt hook accepts an empty third field, so cryptdevice=UUID=x:name:
# is a valid parameter to repair rather than a reason to fail forever.
reset_fixture
cat > "$OMARCHY_LUKS_TRIM_LIMINE_CONF" <<'CONF'
KERNEL_CMDLINE[default]+=" root=UUID=keep-me rw cryptdevice=UUID=keep-me:omarchy_root: rootflags=subvol=@"
CONF
regenerate_boot_conf
run_migration || fail "a parameter with an empty option field must not fail the migration" "$(<"$scratch/output")"
grep -Fq "cryptdevice=UUID=keep-me:omarchy_root:$trim_options" "$OMARCHY_LUKS_TRIM_LIMINE_CONF" ||
  fail "an empty option field gains the full option list" "$(<"$OMARCHY_LUKS_TRIM_LIMINE_CONF")"
assert_options_exactly_once "$OMARCHY_LUKS_TRIM_LIMINE_CONF"
grep -Fq "cryptdevice=UUID=keep-me:omarchy_root:$trim_options" "$OMARCHY_LUKS_TRIM_BOOT_CONF" ||
  fail "the generated entries carry the repaired parameter" "$(<"$OMARCHY_LUKS_TRIM_BOOT_CONF")"
[[ -f $OMARCHY_LUKS_TRIM_MARKER ]] || fail "completion is recorded"
cp "$OMARCHY_LUKS_TRIM_LIMINE_CONF" "$scratch/repaired-limine"
: > "$CALL_LOG"
run_migration || fail "a repaired empty option field stays repaired" "$(<"$scratch/output")"
cmp -s "$OMARCHY_LUKS_TRIM_LIMINE_CONF" "$scratch/repaired-limine" ||
  fail "repairing an empty option field is idempotent" "$(<"$OMARCHY_LUKS_TRIM_LIMINE_CONF")"
pass "a parameter with an empty option field is repaired idempotently"

# A commented-out parameter is not effective: the hook never sees it, so the
# migration must not count it, edit it, or verify against it.
reset_fixture
cat > "$OMARCHY_LUKS_TRIM_LIMINE_CONF" <<'CONF'
# KERNEL_CMDLINE[default]+=" root=UUID=keep-me rw cryptdevice=UUID=keep-me:omarchy_root rootflags=subvol=@"
KERNEL_CMDLINE[default]+=" root=UUID=keep-me rw rd.luks.uuid=keep-me rd.luks.name=keep-me=omarchy_root rootflags=subvol=@"
CONF
regenerate_boot_conf
cp "$OMARCHY_LUKS_TRIM_LIMINE_CONF" "$scratch/original-limine"
run_migration || fail "a comment-only cryptdevice must not fail the migration" "$(<"$scratch/output")"
cmp -s "$OMARCHY_LUKS_TRIM_LIMINE_CONF" "$scratch/original-limine" ||
  fail "commented parameters are never edited" "$(<"$OMARCHY_LUKS_TRIM_LIMINE_CONF")"
[[ ! -s $CALL_LOG ]] || fail "a comment-only cryptdevice does no work" "$(<"$CALL_LOG")"
[[ ! -e $OMARCHY_LUKS_TRIM_MARKER ]] || fail "a comment-only cryptdevice is not marked repaired"
pass "a commented-out cryptdevice= is a clean no-op"

# Each active parameter is repaired on its own: one repaired key does not
# stand in for another.
reset_fixture
cat > "$OMARCHY_LUKS_TRIM_LIMINE_CONF" <<'CONF'
KERNEL_CMDLINE[default]+=" root=UUID=keep-me rw cryptdevice=UUID=keep-me:omarchy_root:allow-discards,no-read-workqueue,no-write-workqueue rootflags=subvol=@"
KERNEL_CMDLINE[fallback]+=" root=UUID=keep-me rw cryptdevice=UUID=keep-me:omarchy_root:allow-discards rootflags=subvol=@"
CONF
regenerate_boot_conf
run_migration || fail "a second cmdline key must not fail the migration" "$(<"$scratch/output")"
grep -Fq "cryptdevice=UUID=keep-me:omarchy_root:$trim_options" "$OMARCHY_LUKS_TRIM_LIMINE_CONF" ||
  fail "the fallback key gains the missing options" "$(<"$OMARCHY_LUKS_TRIM_LIMINE_CONF")"
[[ $(grep -o 'no-read-workqueue' "$OMARCHY_LUKS_TRIM_LIMINE_CONF" | wc -l) == 2 ]] ||
  fail "each key carries the options exactly once" "$(<"$OMARCHY_LUKS_TRIM_LIMINE_CONF")"
cp "$OMARCHY_LUKS_TRIM_LIMINE_CONF" "$scratch/repaired-limine"
: > "$CALL_LOG"
run_migration || fail "a fully repaired config stays repaired" "$(<"$scratch/output")"
cmp -s "$OMARCHY_LUKS_TRIM_LIMINE_CONF" "$scratch/repaired-limine" ||
  fail "repairing every key is idempotent" "$(<"$OMARCHY_LUKS_TRIM_LIMINE_CONF")"
pass "every KERNEL_CMDLINE key is repaired independently and idempotently"

# A build that exits 0 without regenerating the entries leaves stale
# artifacts behind; the config readback cannot see that, the artifacts can.
reset_fixture
if SKIP_ARTIFACT=1 run_migration; then
  fail "a skipped rebuild must fail the migration"
fi
[[ ! -e $OMARCHY_LUKS_TRIM_MARKER ]] || fail "a skipped rebuild stays pending"
grep -Fq "cryptdevice=UUID=keep-me:omarchy_root:$trim_options" "$OMARCHY_LUKS_TRIM_LIMINE_CONF" ||
  fail "the config is repaired even when the build skips" "$(<"$OMARCHY_LUKS_TRIM_LIMINE_CONF")"
! grep -Fq "$trim_options" "$OMARCHY_LUKS_TRIM_BOOT_CONF" ||
  fail "the fixture really left the artifacts stale" "$(<"$OMARCHY_LUKS_TRIM_BOOT_CONF")"
: > "$CALL_LOG"
run_migration || fail "the retry must succeed once the entries regenerate" "$(<"$scratch/output")"
[[ -f $OMARCHY_LUKS_TRIM_MARKER ]] || fail "the retry records completion"
pass "a skipped rebuild is caught by the generated artifacts, not the edited config"

# The refresh stub from the contributor's own harness finally gets used: a
# refresh that fails in a terminal falls back to the next boot.
reset_fixture
if ! REFRESH_FAIL=1 run_migration_pty; then
  fail "a failed live refresh must not fail the migration" "$(<"$scratch/output")"
fi
grep -Fxq 'cryptsetup refresh --allow-discards --perf-no_read_workqueue --perf-no_write_workqueue --persistent omarchy_root' "$CALL_LOG" ||
  fail "the running mapping is still attempted in a terminal" "$(<"$CALL_LOG")"
grep -Fxq 'state set reboot-required' "$CALL_LOG" ||
  fail "a failed refresh falls back to the next boot" "$(<"$CALL_LOG")"
[[ -f $OMARCHY_LUKS_TRIM_MARKER ]] || fail "a failed refresh still records completion"
pass "a failed live refresh falls back to the next boot and still records completion"

# The artifact check is about all three options, not only allow-discards.
source "$helper"
reset_fixture
printf 'cmdline: root=UUID=keep-me rw cryptdevice=UUID=keep-me:omarchy_root:allow-discards rootflags=subvol=@\n' > "$OMARCHY_LUKS_TRIM_BOOT_CONF"
if omarchy_luks_boot_artifacts_trimmed; then
  fail "an artifact with only allow-discards is not trimmed"
fi
printf 'cmdline: root=UUID=keep-me rw cryptdevice=UUID=keep-me:omarchy_root:%s rootflags=subvol=@\n' "$trim_options" > "$OMARCHY_LUKS_TRIM_BOOT_CONF"
omarchy_luks_boot_artifacts_trimmed ||
  fail "an artifact carrying all three options is trimmed" "$(<"$OMARCHY_LUKS_TRIM_BOOT_CONF")"
pass "the artifact check requires all three options, not only allow-discards"

# A stale UKI .cmdline fails the artifact check; the repaired one passes.
require_command objcopy
reset_fixture
omarchy_luks_add_trim_options "$OMARCHY_LUKS_TRIM_LIMINE_CONF"
regenerate_boot_conf
printf 'root=UUID=keep-me rw cryptdevice=UUID=keep-me:omarchy_root' > "$scratch/cmdline-stale"
objcopy --add-section .cmdline="$scratch/cmdline-stale" --set-section-flags .cmdline=contents,alloc,load,readonly,data \
  /bin/true "$scratch/uki/omarchy_linux.efi" 2>/dev/null ||
  fail "the fixture builds a fake UKI"
if omarchy_luks_boot_artifacts_trimmed; then
  fail "a UKI with a stale .cmdline is not trimmed"
fi
printf 'root=UUID=keep-me rw cryptdevice=UUID=keep-me:omarchy_root:%s' "$trim_options" > "$scratch/cmdline-fresh"
objcopy --remove-section .cmdline "$scratch/uki/omarchy_linux.efi" "$scratch/uki/fresh.efi" 2>/dev/null &&
  objcopy --add-section .cmdline="$scratch/cmdline-fresh" --set-section-flags .cmdline=contents,alloc,load,readonly,data \
    "$scratch/uki/fresh.efi" "$scratch/uki/omarchy_linux.efi" 2>/dev/null ||
  fail "the fixture refreshes the fake UKI"
omarchy_luks_boot_artifacts_trimmed ||
  fail "a UKI whose .cmdline carries the options is trimmed"
pass "a stale UKI .cmdline fails the artifact check and a fresh one passes"
